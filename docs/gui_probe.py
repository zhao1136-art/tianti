import tkinter as tk, time
from PIL import ImageGrab
root = tk.Tk()
root.title("tk-test")
root.geometry("320x200+120+120")
tk.Label(root, text="GUI test hello", font=("Microsoft YaHei UI", 14)).pack(pady=40)
root.update()
time.sleep(0.6)
root.update()
x, y = root.winfo_rootx(), root.winfo_rooty()
w, h = root.winfo_width(), root.winfo_height()
img = ImageGrab.grab(bbox=(x, y, x + w, y + h))
img.save(r"G:\天体引擎\docs\gui_probe.png")
print("screenshot ok", img.size, "bbox", x, y, w, h)
root.destroy()
